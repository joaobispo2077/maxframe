import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { pathToFileURL } from 'node:url';

const NO_SCORE =
  'No mutation score. A prefix or other non-exact cache restore does not count as a score.';

function countMutants(report) {
  const counts = {
    Killed: 0,
    Survived: 0,
    Timeout: 0,
    NoCoverage: 0,
    RuntimeError: 0,
    CompileError: 0,
    Ignored: 0,
    Pending: 0,
  };
  for (const file of Object.values(report.files ?? {})) {
    for (const mutant of file.mutants ?? []) {
      const status = mutant.status ?? 'Pending';
      if (status in counts) counts[status] += 1;
      else counts.Pending += 1;
    }
  }
  return counts;
}

function cacheLine(decision) {
  if (decision?.exact === true) return '- **Incremental cache:** exact key.';
  if (decision?.incrementalFileRemoved) {
    return '- **Incremental cache:** prefix restore discarded. It does not count as a score.';
  }
  return '- **Incremental cache:** no restored score.';
}

export function buildMutationSummary({ report, cacheDecision }) {
  const lines = ['## Mutation Tests (Stryker)', ''];
  const discarded =
    cacheDecision?.exact === false && cacheDecision?.incrementalFileRemoved;
  if (!report) {
    lines.push(
      discarded
        ? NO_SCORE
        : 'Mutation report JSON was not found. Check the job logs and the uploaded `mutation-reports` artifact.',
    );
    lines.push('', '_Generated by CI mutation job_');
    return `${lines.join('\n')}\n`;
  }

  const counts = countMutants(report);
  const totalRelevant =
    counts.Killed +
    counts.Survived +
    counts.Timeout +
    counts.NoCoverage +
    counts.RuntimeError +
    counts.CompileError;
  const score =
    totalRelevant > 0
      ? ((counts.Killed + counts.Timeout) / totalRelevant) * 100
      : 0;
  const scoreText = Number.isFinite(score) ? score.toFixed(2) : 'n/a';
  const threshold = report.thresholds?.break;
  const status =
    threshold == null
      ? 'No break threshold configured'
      : score >= Number(threshold)
        ? `Passing (>= ${threshold})`
        : `Failing (< ${threshold})`;

  lines.push(
    '- **Profile:** fast (PR)',
    '- **ignoreStatic:** true',
    '- **Excluded files:** `src/infrastructure/youtube/InMemoryVideoMetadataGateway.ts`',
    '- **Strict weekly backstop:** `stryker-full.yml` (full `src/**`, static mutants run)',
    cacheLine(cacheDecision),
    '',
    `- Mutation score: **${scoreText}%**`,
    `- Threshold: **${threshold ?? 'not set'}**`,
    `- Status: **${status}**`,
    '',
    '| Metric | Count |',
    '|---|---:|',
    `| Killed | ${counts.Killed} |`,
    `| Survived | ${counts.Survived} |`,
    `| Timeout | ${counts.Timeout} |`,
    `| No coverage | ${counts.NoCoverage} |`,
    `| Runtime errors | ${counts.RuntimeError} |`,
    `| Compile errors | ${counts.CompileError} |`,
    `| Ignored | ${counts.Ignored} |`,
    `| Pending/Unknown | ${counts.Pending} |`,
    '',
    '_Generated from `reports/mutation/mutation.json`_',
  );
  return `${lines.join('\n')}\n`;
}

export function assertPrefixRestoreHasNoScore(summary, decision, options = {}) {
  const errors = [];
  const staleMarker = options.staleMarker ?? 'STALE_PREFIX_SCORE_73.37';
  if (decision?.exact !== false) errors.push('expected a non-exact restore');
  if (decision?.scoreCountedFromCache !== false) {
    errors.push('cache score was counted');
  }
  if (decision?.incrementalFileRemoved !== true) {
    errors.push('prefix file was not removed');
  }
  if (!decision?.matchedKey) errors.push('prefix restore did not match a key');
  if (options.exactKey && decision?.matchedKey === options.exactKey) {
    errors.push('restore matched the exact key');
  }
  if (summary.includes(staleMarker)) {
    errors.push('stale score marker leaked into the summary');
  }
  if (/Mutation score:/.test(summary))
    errors.push('a mutation score was reported');
  if (!summary.includes('No mutation score.')) {
    errors.push('summary did not say there is no score');
  }
  return errors;
}

function readJsonIfPresent(path) {
  if (!path || !existsSync(path)) return null;
  return JSON.parse(readFileSync(path, 'utf8'));
}

function isDirectRun() {
  const entry = process.argv[1];
  return Boolean(entry) && import.meta.url === pathToFileURL(entry).href;
}

if (isDirectRun()) {
  const summaryPath =
    process.env.MUTATION_SUMMARY || 'mutation-test-results.md';
  const report = readJsonIfPresent(
    process.env.MUTATION_JSON || 'reports/mutation/mutation.json',
  );
  const cacheDecision = readJsonIfPresent(
    process.env.STRYKER_CACHE_DECISION || 'reports/quality/stryker-cache.json',
  );
  const summary = buildMutationSummary({ report, cacheDecision });
  mkdirSync(dirname(summaryPath), { recursive: true });
  writeFileSync(summaryPath, summary);
  console.log(`Wrote ${summaryPath}`);
}
